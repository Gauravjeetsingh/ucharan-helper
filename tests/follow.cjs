const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const base=process.env.APP_URL||'http://127.0.0.1:8767';
const source=JSON.parse(fs.readFileSync(path.join(__dirname,'../data/lessons/japji-sahib-full.json'),'utf8'));
const section=source.sections.find(s=>s.id==='pauri-1');
const verses=source.verses.filter(v=>section.verse_ids.includes(v.verse_id));
const words=verses.flatMap(v=>v.words);
(async()=>{
  const browser=await chromium.launch({headless:true,...(process.env.BROWSER_EXECUTABLE?{executablePath:process.env.BROWSER_EXECUTABLE}:{})});
  try{
    const page=await browser.newPage({viewport:{width:1280,height:1000}}),errors=[],external=[];
    page.on('pageerror',error=>errors.push(error.message));
    page.on('request',request=>{if(!request.url().startsWith(base)&&!request.url().startsWith('blob:'))external.push(request.url());});
    await page.goto(base+'/follow');
    await page.waitForFunction(()=>!document.getElementById('play').disabled);
    assert.equal(await page.locator('.follow-word').count(),words.length);
    assert.deepEqual(await page.locator('.gurmukhi-line').allTextContents(),verses.map(v=>v.text));
    assert.ok((await page.locator('.phone-shell').boundingBox()).width<=420);
    assert.equal(await page.locator('#record-student,#sound-review').count(),0);
    assert.equal(await page.locator('#play-icon').isVisible(),true);
    assert.equal(await page.locator('#pause-icon').isVisible(),false);
    await page.screenshot({path:path.join(os.tmpdir(),'uchaaran-follow-ready.png'),fullPage:true});
    await page.getByRole('button',{name:'Play audio',exact:true}).click();
    await page.waitForFunction(()=>!document.getElementById('paath').paused);
    assert.equal(await page.locator('#play-icon').isVisible(),false);
    assert.equal(await page.locator('#pause-icon').isVisible(),true);
    // Real audio clock: a future word is red, while the word being recited is green.
    await page.locator(`[data-word-id="${words[1].id}"]`).click();
    assert.equal(await page.locator('#missed').textContent(),'1');
    assert.equal(await page.locator(`[data-word-id="${words[1].id}"]`).getAttribute('data-result'),'missed');
    await page.evaluate(time=>{const audio=document.getElementById('paath');audio.currentTime=time-Number(audio.dataset.referenceStart);},words[0].start+.2);
    await page.locator(`[data-word-id="${words[0].id}"]`).click();
    assert.equal(await page.locator('#caught').textContent(),'1');
    assert.equal(await page.locator(`[data-word-id="${words[0].id}"]`).getAttribute('data-result'),'caught');
    assert.equal(await page.locator('.word-caught').count(),1);
    assert.equal(await page.locator('.word-caught').evaluate(e=>getComputedStyle(e).animationName),'word-catch');
    await page.emulateMedia({reducedMotion:'reduce'});
    assert.equal(await page.locator('.word-caught').evaluate(e=>getComputedStyle(e).animationName),'none');
    await page.emulateMedia({reducedMotion:'no-preference'});
    assert.ok(await page.locator('.word-missed').count()>0);
    const beforeReplay=await page.locator('#caught').innerText();
    await page.locator(`[data-word-id="${words[1].id}"]`).click();
    await page.waitForSelector('.is-replaying');
    await page.waitForFunction(()=>!document.querySelector('.is-replaying'));
    assert.equal(await page.locator('#caught').innerText(),beforeReplay);
    await page.getByRole('button',{name:'Pause audio',exact:true}).click();
    assert.equal(await page.locator('#play-icon').isVisible(),true);
    assert.equal(await page.locator('#pause-icon').isVisible(),false);
    const stopped=await page.locator('#paath').evaluate(audio=>audio.currentTime);
    await page.waitForTimeout(400);
    assert.ok(Math.abs(await page.locator('#paath').evaluate(audio=>audio.currentTime)-stopped)<.02);
    assert.equal(await page.locator('#caught').textContent(),'1');
    await page.screenshot({path:path.join(os.tmpdir(),'uchaaran-follow-playing.png'),fullPage:true});
    await page.getByRole('button',{name:'Start again',exact:true}).click();
    assert.equal(await page.locator('#caught').textContent(),'0');
    assert.equal(await page.locator('#missed').textContent(),'0');
    assert.equal(await page.locator('[data-result="caught"],[data-result="missed"]').count(),0);
    await page.getByRole('button',{name:'Play audio',exact:true}).click();
    await page.waitForFunction(()=>!document.getElementById('paath').paused);
    await page.evaluate(time=>{const audio=document.getElementById('paath');audio.currentTime=time-Number(audio.dataset.referenceStart);},section.end+.02);
    await page.waitForSelector('#results:not([hidden])');
    assert.equal(await page.locator('#play-icon').isVisible(),true);
    assert.equal(await page.locator('#pause-icon').isVisible(),false);
    assert.equal(await page.locator('#result-title').textContent(),`You caught 0 of ${words.length} words`);
    assert.equal(await page.locator('#missed-words .missed-chip').count(),words.length);
    assert.equal(await page.locator('#missed').textContent(),String(words.length));
    await page.getByRole('button',{name:'Play again',exact:true}).click();
    assert.equal(await page.locator('#results').isHidden(),true);
    assert.equal(await page.locator('#play-icon').isVisible(),false);
    assert.equal(await page.locator('#pause-icon').isVisible(),true);
    assert.equal(await page.locator('#missed').textContent(),'0');
    assert.equal(await page.locator('#reader').evaluate(element=>element.scrollTop),0);
    await page.getByRole('button',{name:'Pause audio',exact:true}).click();
    await page.getByRole('button',{name:'Start again',exact:true}).click();
    await page.setViewportSize({width:390,height:844});
    await page.waitForTimeout(100);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    const play=await page.locator('#play').boundingBox();
    assert.ok(play.y+play.height<=844);
    await page.screenshot({path:path.join(os.tmpdir(),'uchaaran-follow-mobile.png'),fullPage:true});
    await page.getByRole('button',{name:'Play audio',exact:true}).click();
    await page.evaluate(time=>{const audio=document.getElementById('paath');audio.currentTime=time-Number(audio.dataset.referenceStart);},section.end+.02);
    await page.waitForSelector('#results:not([hidden])');await page.locator('#next-pauri').click();
    await page.waitForFunction(()=>document.getElementById('pauri-label').textContent==='PAURI 2 OF 38'&&!document.getElementById('play').disabled);
    assert.equal(await page.locator('#caught').innerText(),'0');assert.equal(await page.locator('#missed').innerText(),'0');
    const second=source.sections.find(s=>s.id==='pauri-2');
    assert.deepEqual(await page.locator('.gurmukhi-line').allTextContents(),source.verses.filter(v=>second.verse_ids.includes(v.verse_id)).map(v=>v.text));
    assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
    console.log('PASS: exact Gurmukhi, phone viewport, real audio-clock hits/misses, pause, restart, completion/replay, mobile fit, no external requests.');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
