const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const base=process.env.APP_URL||'http://127.0.0.1:8767';
const source=JSON.parse(fs.readFileSync(path.join(__dirname,'../data/lessons/japji-sahib-full.json'),'utf8'));
const section=source.sections.find(s=>s.id==='pauri-1');
const verses=source.verses.filter(v=>section.verse_ids.includes(v.verse_id));
const words=verses.flatMap(v=>v.words);
(async()=>{
  const browser=await chromium.launch({headless:true,...(process.env.BROWSER_EXECUTABLE?{executablePath:process.env.BROWSER_EXECUTABLE}:{})});
  try{
    const page=await browser.newPage({viewport:{width:1280,height:1000}}),errors=[],external=[];
    page.on('pageerror',error=>errors.push(error.message));
    page.on('request',request=>{if(!request.url().startsWith(base)&&!request.url().startsWith('blob:'))external.push(request.url());});
    await page.addInitScript(() => {
      window.mediaPlayCalls = 0;
      const play = HTMLMediaElement.prototype.play;
      HTMLMediaElement.prototype.play = function(...args) {
        window.mediaPlayCalls++;
        return play.apply(this,args);
      };
    });
    await page.goto(base+'/follow');
    await page.waitForFunction(()=>!document.getElementById('play').disabled);
    assert.equal(await page.locator('.follow-word').count(),words.length);
    assert.deepEqual(await page.locator('.gurmukhi-line').allTextContents(),verses.map(v=>v.text));
    assert.ok((await page.locator('.phone-shell').boundingBox()).width<=420);
    assert.equal(await page.locator('#record-student,#sound-review').count(),0);
    assert.equal(await page.locator('#play-icon').isVisible(),true);
    assert.equal(await page.locator('#pause-icon').isVisible(),false);
    await page.screenshot({path:path.join(os.tmpdir(),'uchaaran-follow-ready.png'),fullPage:true});
    await page.getByRole('button',{name:'Play audio',exact:true}).click();
    await page.waitForFunction(()=>!document.getElementById('paath').paused);
    assert.equal(await page.locator('#play-icon').isVisible(),false);
    assert.equal(await page.locator('#pause-icon').isVisible(),true);
    const inactive=page.locator('.verse:not(.is-active) .follow-word').first();
    assert.equal(await inactive.isDisabled(),true);
    await inactive.evaluate(button=>{button.click();button.dispatchEvent(new MouseEvent('click',{bubbles:true}));});
    assert.equal(await page.locator('#caught').innerText(),'0');
    assert.equal(await page.locator('#missed').innerText(),'0');
    assert.equal(await page.locator('.verse:not(.is-active) .follow-word:enabled').count(),0);
    // Early taps within the active verse remain red; on-time taps are green.
    await page.locator(`[data-word-id="${words[1].id}"]`).click();
    assert.equal(await page.locator('#missed').textContent(),'1');
    assert.equal(await page.locator(`[data-word-id="${words[1].id}"]`).getAttribute('data-result'),'missed');
    await page.evaluate(time=>{const audio=document.getElementById('paath');audio.currentTime=time-Number(audio.dataset.referenceStart);},words[0].start+.2);
    await page.locator(`[data-word-id="${words[0].id}"]`).click();
    assert.equal(await page.locator('#caught').textContent(),'1');
    assert.equal(await page.locator(`[data-word-id="${words[0].id}"]`).getAttribute('data-result'),'caught');
    assert.equal(await page.locator('.word-caught').count(),1);
    assert.equal(await page.locator('.word-caught').evaluate(e=>getComputedStyle(e).animationName),'word-catch');
    await page.emulateMedia({reducedMotion:'reduce'});
    assert.equal(await page.locator('.word-caught').evaluate(e=>getComputedStyle(e).animationName),'none');
    await page.emulateMedia({reducedMotion:'no-preference'});
    assert.ok(await page.locator('.word-missed').count()>0);
    const red=page.locator(`[data-word-id="${words[1].id}"]`);
    assert.equal(await red.isDisabled(),true);
    const beforeRed=await page.evaluate(()=>({plays:window.mediaPlayCalls,time:document.getElementById('paath').currentTime}));
    await red.evaluate(button=>{button.click();button.dispatchEvent(new MouseEvent('click',{bubbles:true}));});
    assert.equal(await page.evaluate(()=>window.mediaPlayCalls),beforeRed.plays,'Red words never start audio');
    assert.equal(await page.locator('#paath').evaluate(audio=>audio.paused),false,'Red words do not interrupt the paath');
    assert.ok(await page.locator('#paath').evaluate(audio=>audio.currentTime)>=beforeRed.time);
    assert.equal(await page.locator('#caught').innerText(),'1');
    assert.equal(await page.locator('.word-replay,.is-replaying').count(),0);
    const nextVerseWord=verses[1].words[0];
    await page.evaluate(time=>{
      const audio=document.getElementById('paath');audio.currentTime=time-Number(audio.dataset.referenceStart);
      audio.dispatchEvent(new Event('timeupdate'));
    },nextVerseWord.start+.05);
    assert.equal(await page.locator(`[data-word-id="${nextVerseWord.id}"]`).isEnabled(),true);
    assert.equal(await page.locator(`[data-word-id="${words[0].id}"]`).isDisabled(),true);
    assert.equal(await page.locator('.verse:not(.is-active) .follow-word:enabled').count(),0);
    await page.getByRole('button',{name:'Pause audio',exact:true}).click();
    assert.equal(await page.locator('#play-icon').isVisible(),true);
    assert.equal(await page.locator('#pause-icon').isVisible(),false);
    assert.equal(await page.locator('.follow-word:enabled').count(),0);
    const pausedPlays=await page.evaluate(()=>window.mediaPlayCalls);
    await red.evaluate(button=>button.dispatchEvent(new MouseEvent('click',{bubbles:true})));
    assert.equal(await page.evaluate(()=>window.mediaPlayCalls),pausedPlays);
    const stopped=await page.locator('#paath').evaluate(audio=>audio.currentTime);
    await page.waitForTimeout(400);
    assert.ok(Math.abs(await page.locator('#paath').evaluate(audio=>audio.currentTime)-stopped)<.02);
    assert.equal(await page.locator('#caught').textContent(),'1');
    await page.screenshot({path:path.join(os.tmpdir(),'uchaaran-follow-playing.png'),fullPage:true});
    await page.getByRole('button',{name:'Start again',exact:true}).click();
    assert.equal(await page.locator('#caught').textContent(),'0');
    assert.equal(await page.locator('#missed').textContent(),'0');
    assert.equal(await page.locator('[data-result="caught"],[data-result="missed"]').count(),0);
    await page.getByRole('button',{name:'Play audio',exact:true}).click();
    await page.waitForFunction(()=>!document.getElementById('paath').paused);
    await page.evaluate(time=>{const audio=document.getElementById('paath');audio.currentTime=time-Number(audio.dataset.referenceStart);},section.end+.02);
    await page.waitForSelector('#results:not([hidden])');
    assert.equal(await page.locator('#play-icon').isVisible(),true);
    assert.equal(await page.locator('#pause-icon').isVisible(),false);
    assert.equal(await page.locator('#result-title').textContent(),`You caught 0 of ${words.length} words`);
    assert.equal(await page.locator('#missed-words .missed-chip').count(),words.length);
    assert.equal(await page.locator('#missed').textContent(),String(words.length));
    assert.equal(await page.locator('#points').innerText(),'0');
    assert.equal(await page.locator('#stars').count(),0);
    assert.equal(await page.locator('.reward-coin').count(),0);
    assert.match(await page.locator('#coin-reward').innerText(),/70%/);
    await page.getByRole('button',{name:'Play again',exact:true}).click();
    assert.equal(await page.locator('#results').isHidden(),true);
    assert.equal(await page.locator('#play-icon').isVisible(),false);
    assert.equal(await page.locator('#pause-icon').isVisible(),true);
    assert.equal(await page.locator('#missed').textContent(),'0');
    assert.equal(await page.locator('#reader').evaluate(element=>element.scrollTop),0);
    await page.getByRole('button',{name:'Pause audio',exact:true}).click();
    await page.getByRole('button',{name:'Start again',exact:true}).click();
    await page.setViewportSize({width:390,height:844});
    await page.waitForTimeout(100);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    const play=await page.locator('#play').boundingBox();
    assert.ok(play.y+play.height<=844);
    await page.screenshot({path:path.join(os.tmpdir(),'uchaaran-follow-mobile.png'),fullPage:true});
    await page.getByRole('button',{name:'Play audio',exact:true}).click();
    await page.evaluate(time=>{const audio=document.getElementById('paath');audio.currentTime=time-Number(audio.dataset.referenceStart);},section.end+.02);
    await page.waitForSelector('#results:not([hidden])');await page.locator('#next-pauri').click();
    await page.waitForFunction(()=>document.getElementById('pauri-label').textContent==='PAURI 2 OF 38'&&!document.getElementById('play').disabled);
    assert.equal(await page.locator('#caught').innerText(),'0');assert.equal(await page.locator('#missed').innerText(),'0');
    const second=source.sections.find(s=>s.id==='pauri-2');
    assert.deepEqual(await page.locator('.gurmukhi-line').allTextContents(),source.verses.filter(v=>second.verse_ids.includes(v.verse_id)).map(v=>v.text));
    const secondWords=source.verses.filter(v=>second.verse_ids.includes(v.verse_id)).flatMap(v=>v.words);
    const catchCount=Math.ceil(secondWords.length*.7);
    async function completeWithCaught(count) {
      await page.getByRole('button',{name:'Play audio',exact:true}).click();
      await page.waitForFunction(()=>!document.getElementById('paath').paused&&!document.getElementById('play').disabled);
      await page.evaluate(({sample,count,end})=>{
        const audio=document.getElementById('paath'), offset=Number(audio.dataset.referenceStart);
        for(const word of sample.slice(0,count)){
          audio.currentTime=(word.start+word.end)/2-offset;
          audio.dispatchEvent(new Event('timeupdate'));
          document.querySelector(`[data-word-id="${word.id}"]`).click();
        }
        audio.currentTime=end+.02-offset;
        audio.dispatchEvent(new Event('timeupdate'));
      },{sample:secondWords,count,end:second.end});
      await page.waitForSelector('#results:not([hidden])');
      assert.equal(await page.locator('#caught').innerText(),String(count));
    }
    // Just below the threshold never awards a coin.
    await completeWithCaught(catchCount-1);
    assert.equal(await page.locator('#points').innerText(),'0');
    assert.equal(await page.locator('.reward-coin').count(),0);
    await page.getByRole('button',{name:'Play again',exact:true}).click();
    await page.getByRole('button',{name:'Pause audio',exact:true}).click();
    await page.getByRole('button',{name:'Start again',exact:true}).click();
    await completeWithCaught(catchCount);
    assert.equal(await page.locator('#points').innerText(),'0','Counter waits for coin arrival');
    assert.equal(await page.locator('.confetti-piece').count(),42);
    assert.equal(await page.locator('.reward-coin').isVisible(),true);
    await page.waitForTimeout(500);
    await page.screenshot({path:path.join(os.tmpdir(),'uchaaran-follow-coin-flight.png'),fullPage:true});
    await page.waitForFunction(()=>document.getElementById('points').value==='1');
    await page.locator('#paath').evaluate(audio=>{
      audio.dispatchEvent(new Event('ended'));audio.dispatchEvent(new Event('timeupdate'));
    });
    assert.equal(await page.locator('#points').innerText(),'1','Repeated completion events do not award again');
    await page.reload();await page.waitForFunction(()=>!document.getElementById('play').disabled);
    assert.equal(await page.locator('#points').innerText(),'1','Total survives refresh');
    await completeWithCaught(catchCount);
    await page.locator('#next-pauri').click();
    await page.waitForFunction(()=>document.getElementById('pauri-label').textContent==='PAURI 3 OF 38'&&!document.getElementById('play').disabled);
    assert.equal(await page.locator('#points').innerText(),'2','Next pauri collects an interrupted coin flight');
    assert.equal(await page.locator('.reward-coin,.confetti-piece').count(),0);
    await page.goto(base+'/follow?pauri=2');await page.waitForFunction(()=>!document.getElementById('play').disabled);
    await page.emulateMedia({reducedMotion:'reduce'});
    await completeWithCaught(catchCount);
    assert.equal(await page.locator('#points').innerText(),'3');
    assert.equal(await page.locator('.reward-coin,.confetti-piece').count(),0);
    assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
    console.log('PASS: exact Gurmukhi, phone viewport, real audio-clock hits/misses, inactive and red words disabled, no word replay, pause, restart, completion/replay, mobile fit, 70% coin threshold, coin flight, accumulated rewards, reduced motion, no external requests.');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
